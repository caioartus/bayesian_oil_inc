export const LINE_H = 10;
const SPACE_W = 3;

const glyphs = {};
for (const [ch, rows] of Object.entries(G)) {
  let w = 0;
  for (const r of rows) for (let i = 0; i < r.length; i++) if (r[i] === '#') w = Math.max(w, i + 1);
  glyphs[ch] = { w, rows };
}

function glyphFor(ch) {
  return glyphs[ch] || glyphs[ch.toUpperCase()] || glyphs['?'];
}

const cache = new Map();
function glyphCanvas(ch, color) {
  const key = ch + color;
  let c = cache.get(key);
  if (c) return c;
  const g = glyphFor(ch);
  c = document.createElement('canvas');
  c.width = Math.max(1, g.w);
  c.height = 8;
  const x = c.getContext('2d');
  x.fillStyle = color;
  g.rows.forEach((r, y) => {
    for (let i = 0; i < r.length; i++) if (r[i] === '#') x.fillRect(i, y, 1, 1);
  });
  cache.set(key, c);
  return c;
}

function charW(ch) {
  if (ch === ' ') return SPACE_W;
  return glyphFor(ch).w;
}

export function textWidth(str) {
  let best = 0;
  for (const line of str.split('\n')) {
    let w = 0;
    let any = false;
    for (const ch of line) {
      if (ch === '*') continue;
      w += charW(ch) + 1;
      any = true;
    }
    best = Math.max(best, any ? w - 1 : 0);
  }
  return best;
}

// Draws one line of text. Returns the highlight state at the end so a
// highlighted phrase can continue onto the next wrapped line.
export function drawText(ctx, str, x, y, color, opts = {}) {
  const { align = 'left', hi = '#ffcd75', shadow = null, scale = 1, maxChars = Infinity } = opts;
  let on = !!opts.hiStart;
  const w = textWidth(str) * scale;
  let cx = Math.round(align === 'center' ? x - w / 2 : align === 'right' ? x - w : x);
  y = Math.round(y);
  let shown = 0;
  for (const ch of str) {
    if (ch === '*') {
      on = !on;
      continue;
    }
    if (shown >= maxChars) break;
    shown++;
    if (ch !== ' ') {
      const g = glyphFor(ch);
      if (shadow) ctx.drawImage(glyphCanvas(ch, shadow), cx + scale, y + scale, g.w * scale, 8 * scale);
      ctx.drawImage(glyphCanvas(ch, on ? hi : color), cx, y, g.w * scale, 8 * scale);
    }
    cx += (charW(ch) + 1) * scale;
  }
  return on;
}

export function wrap(str, maxW) {
  const lines = [];
  for (const para of str.split('\n')) {
    let cur = '';
    for (const word of para.split(' ')) {
      const test = cur ? cur + ' ' + word : word;
      if (textWidth(test) > maxW && cur) {
        lines.push(cur);
        cur = word;
      } else cur = test;
    }
    lines.push(cur);
  }
  return lines;
}

export function visibleLength(str) {
  let n = 0;
  for (const ch of str) if (ch !== '*') n++;
  return n;
}

// Draws pre-wrapped lines, revealing at most `maxChars` characters.
export function drawLines(ctx, lines, x, y, color, opts = {}) {
  let left = opts.maxChars ?? Infinity;
  let hiStart = false;
  lines.forEach((line, i) => {
    if (left <= 0) return;
    hiStart = drawText(ctx, line, x, y + i * (opts.lineH || LINE_H), color, { ...opts, hiStart, maxChars: left });
    left -= visibleLength(line);
  });
}
